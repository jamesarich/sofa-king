#!/usr/bin/env sh
# Writes app/build/Version.xcconfig from the catalog's `sofaking` version, so the iOS and Apple TV hosts carry the same
# version as every other build. XcodeGen runs it as the preGenCommand of app/iosApp and app/tvosApp.
set -eu
app=$(cd "$(dirname "$0")/.." && pwd)
version=$(sed -n 's/^sofaking = "\(.*\)"$/\1/p' "$app/../gradle/libs.versions.toml")
[ -n "$version" ] || { echo "version-xcconfig: no sofaking version in gradle/libs.versions.toml" >&2; exit 1; }
mkdir -p "$app/build"
{
  echo "// Generated by app/tools/version-xcconfig.sh from gradle/libs.versions.toml; do not edit."
  echo "MARKETING_VERSION = $version"
  echo "CURRENT_PROJECT_VERSION = 1"
} > "$app/build/Version.xcconfig"
