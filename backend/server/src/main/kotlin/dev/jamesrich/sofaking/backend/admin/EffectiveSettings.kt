/** How the settings page shows a token: set, generated by the server, or not set. */
internal const val SET = "set"
internal const val GENERATED = "generated"
internal const val UNSET = "not set"

/**
 * The startup settings as the server runs with them, one group per area, each setting once. Tokens are reported only
 * as set, generated or not set. Runtime settings are edited on their own panel and are not listed here.
 */
internal fun effectiveSettings(config: ServerConfig): List<SettingGroup> = SettingArea.entries.mapNotNull { area ->
    val defs = Settings.all.filter { it.area == area && !it.runtime }
    if (defs.isEmpty()) null else SettingGroup(area.title, defs.map { setting(config, it) })
}

private fun setting(config: ServerConfig, def: SettingDef): Setting {
    if (def.type == SettingType.Secret) return secret(config, def)
    val value = def.show(config)?.toString().orEmpty()
    val note = def.note?.invoke(config)
        ?: "Found in SOFA_DATA_DIR; ${def.name} is unset".takeIf { def.name in config.foundInDataDirectory }
    return Setting(def.name, value.ifEmpty { UNSET }, value == def.usual(config)?.toString().orEmpty(), note)
}

private fun secret(config: ServerConfig, def: SettingDef): Setting {
    val value = def.show(config) as String?
    val origin = config.secretOrigins[def.name]
    val shown = when {
        value == null -> UNSET
        origin == SecretOrigin.GENERATED -> GENERATED
        else -> SET
    }
    return Setting(
        def.name,
        shown,
        value == null,
        originNote(config, def.name, origin) + (def.note?.invoke(config) ?: def.help),
    )
}

private fun originNote(config: ServerConfig, name: String, origin: SecretOrigin?): String = when (origin) {
    SecretOrigin.GENERATED -> "Generated and stored in ${config.secretsFile ?: SecretsFile.NAME}. "

    SecretOrigin.FILE -> "Read from the file ${name}_FILE names. "

    SecretOrigin.ENVIRONMENT -> "Set in the environment. "

    SecretOrigin.SAVED ->
        "Saved from the portal in ${config.secretsFile ?: config.dataDirectory.resolve(SecretsFile.NAME)}. "

    null -> ""
}

/** The host of [url] only; a path or query can carry a token. */
private fun hostOf(url: String?): String? = url?.let { runCatching { java.net.URI(it).host }.getOrNull() }

internal fun providerSummary(config: FeedConfig): SourceSummary {
    val notes = buildList {
        if (config.headers.isNotEmpty()) add("headers: ${config.headers.keys.sorted().joinToString()}")
        if (config.options.isNotEmpty()) add("options: ${config.options.keys.sorted().joinToString()}")
        if (!config.probe) add("not probed")
        if (config.guideUrl != null) add("guide from ${hostOf(config.guideUrl) ?: "a URL"}")
    }
    val kind = if (config.native) "native: ${config.service}" else "M3U"
    val where = if (config.native) "built-in client" else hostOf(config.playlistUrl) ?: "a URL"
    return SourceSummary(config.id, kind, where, every(config.refreshInterval), notes)
}

internal fun guideSummary(config: GuideConfig): SourceSummary {
    val headers = config.headers.keys.sorted().joinToString()
    val notes = if (config.headers.isEmpty()) emptyList() else listOf("headers: $headers")
    val kind = if (config.provider != null) "provider guide" else "XMLTV"
    val where = config.provider?.let { "provider $it" } ?: hostOf(config.url) ?: "a URL"
    return SourceSummary(config.id, kind, where, every(config.refreshSeconds), notes)
}

private fun every(seconds: Long): String {
    val period = Duration.ofSeconds(seconds)
    return when {
        period.toSecondsPart() == 0 && period.toMinutesPart() == 0 -> "every ${period.toHours()} h"
        period.toSecondsPart() == 0 -> "every ${period.toMinutes()} min"
        else -> "every $seconds s"
    }
}
